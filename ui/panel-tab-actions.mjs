import { icon } from "./icons.mjs";

// Tab gestures stay in the owning conversation. Delayed menu actions hold the
// actual tab objects, so a new tab or another conversation cannot inherit them.
export class PanelTabActions {
  constructor({ context, close, reopen, move, copy, reveal, external, changed, error }) {
    Object.assign(this, { context, close, reopen, move, copy, reveal, external, changed, error });
    document.addEventListener("contextmenu", e => {
      const tab = this.target(e.target); if (!tab) return;
      e.preventDefault(); this.open(tab, { x: e.clientX, y: e.clientY });
    });
    document.addEventListener("pointerdown", e => {
      // Suppress only the click generated by the completed drag. A fresh
      // pointer press starts a new gesture and must remain actionable.
      this.suppressClick = 0;
      if (this.menu && !this.menu.contains(e.target)) this.dismiss(false);
      const tab = this.target(e.target); if (!tab) return;
      if (e.button === 1) { e.preventDefault(); return; }
      if (e.button !== 0 || !e.target.closest('[role="tab"]')) return;
      this.drag = { ...tab, pointer: e.pointerId, x: e.clientX, y: e.clientY, active: false };
    });
    document.addEventListener("auxclick", e => {
      if (e.button !== 1) return;
      const tab = this.target(e.target); if (!tab) return;
      e.preventDefault(); this.run(() => this.close(tab.context.owner, [tab.tab]));
    });
    document.addEventListener("pointermove", e => this.pointerMove(e));
    document.addEventListener("pointerup", e => this.pointerEnd(e));
    document.addEventListener("pointercancel", () => this.cancelDrag());
    document.documentElement.addEventListener("lostpointercapture", () => this.cancelDrag());
    document.addEventListener("click", e => {
      if (!this.suppressClick || performance.now() > this.suppressClick) return;
      this.suppressClick = 0; e.preventDefault(); e.stopImmediatePropagation();
    }, true);
    document.addEventListener("keydown", e => this.key(e));
    window.addEventListener("blur", () => { this.cancelDrag(); this.dismiss(false); });
    window.addEventListener("resize", () => this.dismiss(false));
  }
  run(operation) { Promise.resolve().then(operation).catch(this.error); }
  target(node) {
    const row = node.closest?.('.work-tabs-bar [data-tab-key]'), context = this.context();
    if (!row || !context || row.closest(".browser-tabs")?.dataset.owner !== context.owner) return;
    const tab = context.tabs.find(tab => tab.key === row.dataset.tabKey);
    return tab && { context, tab, key: tab.key };
  }
  valid(value) {
    const now = this.context();
    return now && now.owner === value.context.owner && now.tabs.includes(value.tab) && value.tab.key === value.key;
  }
  signature(context) { return context && JSON.stringify([context.owner, context.selected, context.tool, context.canReopen, context.tabs.map(tab => tab.key)]); }
  refresh() {
    if (this.menu && this.signature(this.context()) !== this.menuSignature) this.dismiss(false);
    if (this.drag && !this.valid(this.drag)) this.cancelDrag();
    if (this.drag?.active) this.decorateDrag();
  }
  dismiss(focus = true) {
    if (!this.menu) return;
    this.menu.remove(); this.menu = null; this.changed();
    if (focus && this.menuSource && this.valid(this.menuSource)) {
      const button = this.button(this.menuSource.key); button?.focus({ preventScroll: true });
    }
    this.menuSource = null;
  }
  button(key) {
    return [...document.querySelectorAll('.work-tabs-bar [data-action="panel-select-tab"]')].find(button => button.dataset.key === key);
  }
  open(source, point) {
    this.cancelDrag(); this.dismiss(false);
    const { context, tab } = source, index = context.tabs.indexOf(tab), url = context.url(tab);
    const others = context.tabs.filter(value => value !== tab), right = context.tabs.slice(index + 1);
    const items = [
      ["关闭标签页", "close", () => this.close(context.owner, [tab])],
      ["关闭其他标签页", "close", (others.length || context.tool) && (() => this.close(context.owner, others, context.tool ? { page: context.tool, keep: tab } : undefined))],
      ["关闭右侧标签页", "close", right.length && (() => this.close(context.owner, right))],
      ["重新打开关闭的标签页", "clock", context.canReopen && (() => this.reopen(context.owner))],
      tab.kind === "file" ? ["复制文件路径", "copy", () => this.copy(tab.file)] : ["复制网页地址", "copy", url && (() => this.copy(url))],
      tab.kind === "file" ? ["在文件夹中显示", "folder", () => this.reveal(context.workspace, tab.file)] : ["在系统浏览器打开", "external", url && (() => this.external(url))],
    ];
    document.querySelector(".context-menu")?.remove();
    const menu = document.createElement("div"); menu.className = "context-menu panel-tab-menu";
    menu.setAttribute("role", "menu"); menu.setAttribute("aria-label", "标签页操作");
    for (const [label, glyph, operation] of items) {
      const button = document.createElement("button"), text = document.createElement("span");
      button.type = "button"; button.setAttribute("role", "menuitem"); button.disabled = !operation;
      button.innerHTML = icon(glyph); text.textContent = label; button.append(text);
      button.addEventListener("click", e => {
        e.stopPropagation();
        const valid = this.valid(source); this.dismiss();
        if (valid && operation) this.run(operation);
      });
      menu.append(button);
    }
    this.menu = menu; this.menuSource = source; this.menuSignature = this.signature(context);
    document.body.append(menu);
    const rect = this.button(source.key)?.getBoundingClientRect();
    menu.style.left = `${Math.max(8, Math.min(innerWidth - menu.offsetWidth - 8, point?.x ?? rect?.left ?? 8))}px`;
    menu.style.top = `${Math.max(8, Math.min(innerHeight - menu.offsetHeight - 8, point?.y ?? rect?.bottom ?? 8))}px`;
    menu.querySelector("button:not(:disabled)")?.focus(); this.changed();
  }
  key(e) {
    if (this.menu && this.menu.contains(e.target)) {
      const buttons = [...this.menu.querySelectorAll("button:not(:disabled)")], index = buttons.indexOf(document.activeElement);
      if (["ArrowDown", "ArrowUp", "Home", "End", "Escape", "Tab"].includes(e.key)) {
        e.preventDefault(); e.stopImmediatePropagation();
        if (e.key === "Escape" || e.key === "Tab") return this.dismiss();
        buttons[e.key === "Home" ? 0 : e.key === "End" ? buttons.length - 1 : (index + (e.key === "ArrowDown" ? 1 : buttons.length - 1)) % buttons.length]?.focus();
      }
      return;
    }
    if (e.key === "Escape" && this.drag?.active) { e.preventDefault(); this.cancelDrag(); return; }
    if (e.key === "ContextMenu" || e.key === "F10" && e.shiftKey) {
      const source = this.target(e.target); if (!source) return;
      e.preventDefault(); this.open(source);
    }
  }
  pointerMove(e) {
    const drag = this.drag;
    if (!drag || e.pointerId !== drag.pointer) return;
    if (!this.valid(drag) || !e.buttons) return this.cancelDrag();
    if (!drag.active && Math.hypot(e.clientX - drag.x, e.clientY - drag.y) < 6) return;
    if (!drag.active) {
      drag.active = true; document.documentElement.setPointerCapture(e.pointerId);
      document.documentElement.classList.add("reordering-panel-tabs");
    }
    e.preventDefault();
    const strip = document.querySelector(".work-tabs-bar .browser-tabs"), rect = strip?.getBoundingClientRect();
    drag.target = null;
    if (rect && e.clientY >= rect.top - 10 && e.clientY <= rect.bottom + 10 && e.clientX >= rect.left - 10 && e.clientX <= rect.right + 10) {
      if (e.clientX < rect.left + 25) strip.scrollLeft -= 18;
      else if (e.clientX > rect.right - 25) strip.scrollLeft += 18;
      const rows = [...strip.querySelectorAll("[data-tab-key]")].filter(row => row.dataset.tabKey !== drag.key);
      const row = rows.find(row => e.clientX < row.getBoundingClientRect().right) || rows.at(-1);
      if (row) {
        const bounds = row.getBoundingClientRect(); drag.target = row.dataset.tabKey; drag.after = e.clientX >= bounds.left + bounds.width / 2;
      }
    }
    this.decorateDrag();
  }
  decorateDrag() {
    const drag = this.drag;
    for (const row of document.querySelectorAll(".work-tabs-bar [data-tab-key]")) {
      row.classList.toggle("tab-dragging", row.dataset.tabKey === drag?.key);
      row.classList.toggle("tab-drop-before", row.dataset.tabKey === drag?.target && !drag.after);
      row.classList.toggle("tab-drop-after", row.dataset.tabKey === drag?.target && drag.after);
    }
  }
  cancelDrag() {
    const drag = this.drag; this.drag = null;
    if (drag?.active) this.suppressClick = performance.now() + 250;
    document.documentElement.classList.remove("reordering-panel-tabs"); this.decorateDrag();
    if (drag?.active && document.documentElement.hasPointerCapture(drag.pointer)) document.documentElement.releasePointerCapture(drag.pointer);
  }
  pointerEnd(e) {
    const drag = this.drag; if (!drag || e.pointerId !== drag.pointer) return;
    const valid = this.valid(drag); this.cancelDrag();
    if (!drag.active) return;
    this.suppressClick = performance.now() + 250;
    if (valid && drag.target) this.move(drag.context.owner, drag.key, drag.target, drag.after);
  }
}
